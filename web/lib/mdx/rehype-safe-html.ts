// Runs after rehype-raw. Keeps the page self-contained and safe:
// - images become a placeholder rendered on the server (no <img> to external hosts; the source images are
//   signed Coursera URLs that have expired), with the alt text and a link to the lesson on Coursera,
// - iframes/video/audio/embeds become a plain link,
// - unknown or unsafe raw HTML tags are shown as literal text (content often mentions tags like <script>),
// - event-handler attributes and javascript: URLs are dropped, inline styles keep only a few layout and text
//   properties (no url(), no custom properties: a `--shiki` style would be lifted into the page's stylesheet),
// - every node with children is walked, also the MDX Callouts of `:::` blocks and raw <pre>/<code> (security audit
//   P-01): this runs before Shiki, so a markdown code block is only pre > code > text here and its text is untouched.
import fs from 'node:fs';
import path from 'node:path';
import type { Element, ElementContent, Root, Text } from 'hast';
import type { VFile } from 'vfile';
import { CONTENT_DIR } from '../content/config';
import { tVi, type T } from '../i18n/translate';
import { getBook } from '../books';

// image URL (without query) -> Coursera lesson URL, generated by scripts/extract-courses.mjs
let imageSources: Record<string, string> | null = null;
function lessonUrlFor(src: string): string | undefined {
  if (!imageSources) {
    try {
      imageSources = JSON.parse(fs.readFileSync(path.join(CONTENT_DIR, '..', 'image-sources.json'), 'utf8'));
    } catch {
      imageSources = {};
    }
  }
  return imageSources![src.split('?')[0]];
}

/** Book slug of the markdown file being compiled (<CONTENT_DIR>/<track>/<book>/...). */
function bookOf(file: VFile): string | undefined {
  if (!file.path) return undefined;
  return path.relative(CONTENT_DIR, file.path).split(path.sep)[1];
}

const ALLOWED = new Set(
  (
    'a abbr b blockquote br caption center code col colgroup dd del details div dl dt em figcaption figure ' +
    'h1 h2 h3 h4 h5 h6 hr i ins kbd li mark ol p pre q s samp small span strong sub summary sup ' +
    'table tbody td tfoot th thead tr u ul var input section article header footer nav aside main time cite'
  ).split(' '),
);
const EMBEDS = new Set(['iframe', 'video', 'audio', 'embed', 'object', 'source']);

const hostOf = (url: unknown) => {
  try {
    return new URL(String(url)).host;
  } catch {
    return '';
  }
};

const text = (value: string): Text => ({ type: 'text', value });

function el(tagName: string, className: string, children: ElementContent[], props: Element['properties'] = {}): Element {
  return { type: 'element', tagName, properties: { className: [className], ...props }, children };
}

function imagePlaceholder(node: Element, file: VFile, t: T): Element {
  const alt = String(node.properties?.alt ?? '').trim();
  const src = String(node.properties?.src ?? '');
  const host = hostOf(src);
  // the lesson that contains the image, else the book's first Coursera course page
  const book = getBook(bookOf(file) ?? '');
  const lesson = /coursera|cloudfront/.test(host) ? lessonUrlFor(src) : undefined;
  const course = /coursera|cloudfront/.test(host) ? book?.courseraUrls.find((c) => c.url)?.url : undefined;
  const target = lesson ?? course;
  const note: ElementContent[] = [text(`${t('Ảnh gốc không có bản offline.')} `)];
  if (target)
    note.push(
      el('a', 'img-missing-link', [text(lesson ? t('Xem ảnh trên Coursera') : t('Xem khóa học trên Coursera'))], {
        href: target,
        target: '_blank',
        rel: ['noreferrer'],
      }),
    );
  return el('span', 'img-missing', [
    el('span', 'img-missing-icon', [text('🖼')], { ariaHidden: 'true' }),
    el(
      'span',
      'img-missing-text',
      [
        // the image's stand-in, named by its alt; the note with its link stays outside it, since what is inside an
        // img is not read and a link there could not be reached by a screen reader (axe nested-interactive). The
        // lesson around it is lang="vi" (its own alt too); the placeholder's words are in the page's language
        el('span', 'img-missing-alt', [text(alt ? t('Hình minh họa: {alt}', { alt }) : t('Hình minh họa'))], {
          role: 'img',
          ariaLabel: alt || t('Hình minh họa'),
          lang: alt ? 'vi' : t.locale,
        }),
        el('span', 'img-missing-note', note),
      ],
      { lang: t.locale },
    ),
  ]);
}

function embedPlaceholder(node: Element, t: T): Element {
  const src = String(node.properties?.src ?? '');
  const host = hostOf(src);
  const label = host ? t('Nội dung nhúng từ {host} (mở ở trang gốc)', { host }) : t('Nội dung nhúng (mở ở trang gốc)');
  return el(
    'span',
    'embed-missing',
    src && /^https?:/.test(src)
      ? [el('a', 'embed-missing-link', [text(label)], { href: src, target: '_blank', rel: ['noreferrer'] })]
      : [text(label)],
    { lang: t.locale },
  );
}

function literal(node: Element, file: VFile): Text {
  const start = node.position?.start.offset;
  const end = node.position?.end.offset;
  if (start !== undefined && end !== undefined) return text(String(file.value).slice(start, end));
  return text(`<${node.tagName}>`);
}

/** Inline style properties content may keep (handbooks use them for widths, colours and alignment). */
const STYLE_PROPS = new Set(
  (
    'color background-color text-align font-weight font-style font-size text-decoration vertical-align width ' +
    'max-width min-width height max-height border border-radius margin-left margin-right display gap float'
  ).split(' '),
);

/** The declarations of `style` whose property is allowed and whose value cannot fetch or escape: or null. */
export function safeStyle(style: string): string | null {
  const kept = style
    .split(';')
    .map((d) => d.trim())
    .filter((d) => {
      const i = d.indexOf(':');
      if (i < 1) return false;
      const prop = d.slice(0, i).trim().toLowerCase();
      const value = d.slice(i + 1).trim().toLowerCase();
      return STYLE_PROPS.has(prop) && value.length > 0 && !/url\(|expression|image|var\(|[\\@<>{}]|\/\*/.test(value);
    });
  return kept.length ? kept.join('; ') : null;
}

function clean(node: Element) {
  const props = node.properties ?? {};
  for (const key of Object.keys(props)) {
    if (/^on/i.test(key)) delete props[key];
    if ((key === 'href' || key === 'src') && /^\s*javascript:/i.test(String(props[key]))) delete props[key];
    if (key === 'style') {
      const style = safeStyle(String(props[key]));
      if (style) props[key] = style;
      else delete props[key];
    }
  }
}

type Parent = { children: ElementContent[] | Root['children'] };
const hasChildren = (node: unknown): node is Parent =>
  typeof node === 'object' && node !== null && Array.isArray((node as Parent).children);

/** `t`: the language of the placeholders' words (lib/content/compile.ts compiles once per language). */
export function rehypeSafeHtml({ t = tVi }: { t?: T } = {}) {
  return (tree: Root, file: VFile) => {
    const visit = (parent: Parent) => {
      parent.children = (parent.children as unknown[]).map((child) => {
        if (typeof child !== 'object' || child === null) return child;
        const node = child as Element;
        if (node.type !== 'element') {
          // MDX nodes (a `:::` Callout, mdxJsxTextElement) and anything else with children: clean what is inside
          if (hasChildren(node)) visit(node);
          return node;
        }
        // local images (backfilled into public/img/) are kept, everything else becomes a placeholder
        if (node.tagName === 'img' && String(node.properties?.src ?? '').startsWith('/img/')) {
          node.properties = { src: node.properties.src, alt: node.properties.alt ?? '', loading: 'lazy' };
          return node;
        }
        if (node.tagName === 'img') return imagePlaceholder(node, file, t);
        if (EMBEDS.has(node.tagName)) return embedPlaceholder(node, t);
        if (!ALLOWED.has(node.tagName)) return literal(node, file);
        clean(node);
        visit(node);
        return node;
      }) as typeof parent.children;
    };
    visit(tree);
  };
}
